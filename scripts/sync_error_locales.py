def camel(code: str) -> str:
    return re.sub(r"_([a-z0-9])", lambda m: m.group(1).upper(), code)


def main() -> None:
    from src.kernel.errors import ErrorCode

    # 枚举码 → (camelKey, en 文案)
    enum_entries: dict[str, str] = {}
    for member in ErrorCode:
        enum_entries[camel(member.code)] = member.default_message

    for locale in ["en", "zh", "ja", "ko", "ru"]:
        path = LOCALES_DIR / f"{locale}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        section = data.setdefault("backendErrors", {})
        added = 0
        for key, en_msg in enum_entries.items():
            if key in section:
                continue
            if locale == "en":
                section[key] = en_msg
            else:
                trans = TRANSLATIONS.get(key, {}).get(locale)
                if trans is None:
                    raise SystemExit(f"缺少翻译: {locale}.{key}")
                section[key] = trans
            added += 1
        # 前端自有 key
        if "forceRelogin" not in section:
            section["forceRelogin"] = (
                "User permissions have changed. Please log in again"
                if locale == "en"
                else TRANSLATIONS["forceRelogin"][locale]
            )
            added += 1
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"{locale}: 新增 {added} 个 backendErrors key")


if __name__ == "__main__":
    main()
